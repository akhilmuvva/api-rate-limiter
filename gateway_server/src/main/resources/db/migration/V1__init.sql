-- NT14 gateway durable storage. Timestamps are TIMESTAMPTZ (UTC).
-- IPs are never stored in clear text in request_logs/clients: client_id holds either
-- "user:<email>" or a masked IP ("ip:203.0.113.x"), and client_ip_hash is HMAC-SHA256(IP, IP_HASH_SALT).

CREATE TABLE request_logs (
    id             BIGINT       PRIMARY KEY,             -- time-ordered id generated by the gateway (ms << 16 | seq)
    ts             TIMESTAMPTZ  NOT NULL,
    client_id      TEXT         NOT NULL,
    client_ip_hash TEXT,
    method         TEXT         NOT NULL,
    path           TEXT         NOT NULL,
    status         INT          NOT NULL,
    latency_ms     BIGINT       NOT NULL,
    decision       TEXT         NOT NULL,
    source         TEXT         NOT NULL CHECK (source IN ('real', 'demo')),
    upstream       TEXT
);
CREATE INDEX idx_request_logs_ts      ON request_logs (ts);
CREATE INDEX idx_request_logs_client  ON request_logs (client_id, id DESC);
CREATE INDEX idx_request_logs_iphash  ON request_logs (client_ip_hash, id DESC);
CREATE INDEX idx_request_logs_status  ON request_logs (status, id DESC);

CREATE TABLE metrics_1m (
    minute     TIMESTAMPTZ NOT NULL,
    endpoint   TEXT        NOT NULL,
    source     TEXT        NOT NULL CHECK (source IN ('real', 'demo')),
    requests   BIGINT      NOT NULL,
    allowed    BIGINT      NOT NULL,
    throttled  BIGINT      NOT NULL,
    errors     BIGINT      NOT NULL,                    -- upstream/server errors (status >= 500)
    p50        DOUBLE PRECISION NOT NULL,
    p95        DOUBLE PRECISION NOT NULL,
    latency_sum_ms BIGINT  NOT NULL DEFAULT 0,          -- lets reports compute an exact average latency
    PRIMARY KEY (minute, endpoint, source)
);
CREATE INDEX idx_metrics_1m_minute ON metrics_1m (minute);

CREATE TABLE clients (
    id              TEXT        PRIMARY KEY,            -- "user:<email>" or "iphash:<hmac>"
    label           TEXT        NOT NULL,               -- masked display value
    source          TEXT        NOT NULL DEFAULT 'real',
    first_seen      TIMESTAMPTZ NOT NULL,
    last_seen       TIMESTAMPTZ NOT NULL,
    total_requests  BIGINT      NOT NULL DEFAULT 0,
    throttled_count BIGINT      NOT NULL DEFAULT 0
);

-- Bans must be enforceable after a restart, so client_key holds the exact key the limiter uses.
CREATE TABLE bans (
    client_key  TEXT        PRIMARY KEY,
    reason      TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ NOT NULL,
    created_by  TEXT
);

CREATE TABLE rules (
    endpoint_id   TEXT        PRIMARY KEY,
    limit_per_min INT         NOT NULL,
    burst_limit   INT         NOT NULL,
    action        TEXT        NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE incidents (
    id          TEXT        PRIMARY KEY,
    ts          TIMESTAMPTZ NOT NULL,
    type        TEXT        NOT NULL,
    severity    TEXT        NOT NULL,
    detail      TEXT        NOT NULL,
    target_id   BIGINT,
    resolved_at TIMESTAMPTZ
);
CREATE INDEX idx_incidents_ts ON incidents (ts DESC);

CREATE TABLE monitored_targets (
    id              BIGSERIAL   PRIMARY KEY,
    name            TEXT        NOT NULL UNIQUE,
    url             TEXT        NOT NULL,
    method          TEXT        NOT NULL DEFAULT 'GET',
    expected_status INT         NOT NULL DEFAULT 200,
    interval_sec    INT         NOT NULL DEFAULT 30 CHECK (interval_sec BETWEEN 5 AND 3600),
    timeout_ms      INT         NOT NULL DEFAULT 10000 CHECK (timeout_ms BETWEEN 500 AND 60000),
    enabled         BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE probe_results (
    id          BIGSERIAL   PRIMARY KEY,
    target_id   BIGINT      NOT NULL REFERENCES monitored_targets (id) ON DELETE CASCADE,
    ts          TIMESTAMPTZ NOT NULL,
    up          BOOLEAN     NOT NULL,
    status_code INT,
    latency_ms  BIGINT      NOT NULL,
    error       TEXT,
    transition  TEXT                                      -- NULL, 'up->down' or 'down->up'
);
CREATE INDEX idx_probe_results_target_ts ON probe_results (target_id, ts DESC);

